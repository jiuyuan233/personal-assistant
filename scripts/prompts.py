# ---------------------------------------------------------------------------
# 公告相关度
# ---------------------------------------------------------------------------
NOTICE_SCHEMA = """\
[{"index": 0, "score": 0, "category": "", "reason": "", "deadline": null, "tags": []}]"""

NOTICE_INSTRUCTIONS = f"""\
你是大学校园公告筛选器。根据用户画像，给每条公告打相关度分。

用户画像：
{USER_PROFILE}

评分标准（score 为 0-5 的整数）：
5 = 必须行动：有明确报名/提交截止日期，且用户可直接参与的竞赛、大创、项目、奖学金
4 = 强烈建议：与用户专业或 AI 兴趣高度相关的竞赛、科研、实习、技能认证
3 = 值得知道：面向全体学生的有益机会（讲座、培训、志愿者、双选会）
2 = 弱相关：需要特定身份或条件，用户可能不符合
1 = 基本无关：行政通知、面向教师、党建、后勤
0 = 完全无关：放假、调课、值班、会议报道、新闻宣传

category 从这几个里选一个：竞赛 / 创新创业 / 科研 / 奖学金 / 实习就业 / 讲座培训 / 证书考试 / 其他
deadline：如果标题或常识能判断出报名截止日期，输出 "YYYY-MM-DD"，否则 null。不要编造。
reason：一句话说明为什么给这个分，20 字以内。
tags：1-3 个短标签。

只输出 JSON 数组，index 必须与输入序号一一对应，不要遗漏任何一条。"""


def notice_messages(items: list[dict]) -> list[dict]:
    lines = []
    for i, n in enumerate(items):
        lines.append(f'{i}. [{n.get("publish_date") or "日期未知"}] [{n.get("source") or ""}] {n.get("title") or ""}')
    return [{
        "role": "user",
        "content": NOTICE_INSTRUCTIONS + "\n\n待评分公告：\n" + "\n".join(lines),
    }]


# ---------------------------------------------------------------------------
# 日记挖掘：名言 + 潜在计划
# ---------------------------------------------------------------------------
DIARY_SCHEMA = """\
{"quotes": [{"text": "", "context": ""}],
 "plans": [{"text": "", "due_date": null, "confidence": 0.0, "state": "open", "tags": []}]}"""

DIARY_INSTRUCTIONS = f"""\
你在读用户自己写的日记/笔记。从中抽取两类东西，不要总结、不要评论、不要改写原文意思。

用户画像：
{USER_PROFILE}

一、quotes（名言）
用户写下的、带有个人态度或自我激励性质的句子。判定标准：
- 是用户自己的话，不是抄录的名人名言、歌词、书摘（抄录的不要）
- 有观点、有情绪、有自我要求，例如「我要…」「不能再…」「…才是真的…」
- 不是流水账（「今天上了高数课」不算）
text 必须是原文摘录，一字不改，可以去掉首尾空白和 Markdown 标记。
context 用一句话说明这句话出现的语境，15 字以内。
宁缺毋滥：一篇日记里通常 0-2 条，没有就返回空数组。

二、plans（潜在计划）
注意：Markdown 复选框 `- [ ]` / `- [x]` 已经由程序确定性解析过了，**不要重复输出复选框里的待办**。
你只负责挖那些没有写成复选框的意图：
- 正文里明说但没列成待办的事：「下周要交…」「打算报名…」
- 隐含的意图：「一直想学…」「要是能…就好了」「该把…捡起来了」
- 反复出现的念头（即使没写成待办）
text 用一句话概括这个计划，20 字以内，保留用户原意的关键词。
due_date：日记里能推断出的截止时间 "YYYY-MM-DD"，推断不出就 null。不要编造。
confidence：0.0-1.0，明说的事给 0.9，强烈意图给 0.7，模糊念头给 0.4。
state：一律 "open"（是否完成由人工在 data/diary/plans.json 里改，你不要判断）。
tags：1-3 个短标签，如 学习 / 竞赛 / 健康 / 技能 / 生活。
不要把已经明确写完的事当成计划。

只输出 JSON，两个键都必须存在，没有内容就给空数组。"""


def diary_messages(text: str, source_file: str, source_date: str) -> list[dict]:
    return [{
        "role": "user",
        "content": (DIARY_INSTRUCTIONS
                    + f"\n\n文件名：{source_file}\n文件日期：{source_date or '未知'}\n"
                    + f"\n--- 日记正文开始 ---\n{text}\n--- 日记正文结束 ---"),
    }]


