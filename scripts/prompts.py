# ---------------------------------------------------------------------------
# 飞书三时段推送：早 7 点作业+公告+一言+图 / 中午问好鼓励 / 晚上日记总结
# ---------------------------------------------------------------------------
# ⚠️ 分工：AI 只写「人话」（问好/调侃/鼓励/总结）。作业清单、公告清单、一言、二次元图
# 由 daily_push.info_block() 与 notify_feishu.js 确定性拼在 AI 文字后面，**不经过 AI**。
# 所以提示词里必须明确「不要复述清单」，否则 AI 会把清单抄一遍，消息翻倍还漏条目。
PUSH_KIND_BRIEF = {
    "morning": ("早上 7 点的中文问好。先损一句再落到一句实在的鼓励，可以提「作业和公告我给你列在下面了」、"
                "「图也给你带了」，但**不要复述清单里的任何条目、日期、链接**。"
                "**绝对不要提课表、不要提上课时间**（用户明确说课表提醒不用你管）。"),
    "noon": ("中午的问好与鼓励。先损一句再给一句具体的鼓励。"
             "不许编造上午发生了什么——事实里没有的就是没发生。不要复述清单。"),
    "night": ("晚上对这一天做个小结。事实里只有今天日记里摘出来的话（若有）——围绕它"
              "聊一两句就够，再给明天一个具体动作。没有名言就直接道晚安，不许编造"
              "今天发生了什么。不要复述清单。"),
}

PUSH_RULES = f"""\
你在给用户发飞书消息，不是写报告。

{PERSONA}

用户画像：
{USER_PROFILE}

写作要求：
- 直接输出消息正文。不要 JSON、不要 Markdown 代码块、不要「好的」之类开场、不要解释你在做什么。
- 中文口语短句。早上和中午 100 字以内，晚上 160 字以内。
- **你只写人话部分**。作业清单、公告清单、一言、图片会由程序附在你这段文字后面，
  所以**不要复述清单条目、不要抄日期和链接、不要自己加「今日一言」段落**。
- **只能用「今日事实」里给出的信息**。不许编造任务、日期、成绩、课程、活动。
- 事实里没有任务就直说没有，不许硬凑，也不许拿课表来填。
- 给了「一言」就自然提一句（可以吐槽它），但**不许改它的字**，也不要整段抄录。
- 提到图片时只说「给你带了张图」这类话，**不许描述画面内容**——你看不到图，描述就是编造。
- 损的对象是拖延和借口，不是用户这个人。收尾必须落到一句实在的话上。
"""


def push_messages(kind: str, facts: str, hitokoto: str) -> list[dict]:
    brief = PUSH_KIND_BRIEF.get(kind, PUSH_KIND_BRIEF["morning"])
    content = PUSH_RULES + f"\n本次时段：{brief}\n\n今日事实：\n{facts}\n"
    if hitokoto:
        content += f"\n一言（原文，不许改字）：{hitokoto}\n"
    return [{"role": "user", "content": content}]


