COMMENT_SCHEMA = '{"comments": ["", ""]}'

COMMENT_INSTRUCTIONS = f"""\
给下面这些从用户日记里摘出来的句子逐条写点评。

{PERSONA}

要求：
- 每条 40 字以内，必须针对这句话本身：指出它体现了什么、哪里在自我欺骗、
  或下一步具体该做什么。不许空泛夸奖，不许复述原句。
- 按输入序号一一对应，输出 JSON：{{"comments": ["第0条点评", "第1条点评", ...]}}
- 数组长度必须等于输入条数，没话说的给空字符串，不要跳过。"""


def comment_messages(items: list[dict]) -> list[dict]:
    lines = [f'{i}. 「{q.get("text") or ""}」（语境：{q.get("context") or "未知"}）'
             for i, q in enumerate(items)]
    return [{"role": "user",
             "content": COMMENT_INSTRUCTIONS + "\n\n待点评：\n" + "\n".join(lines)}]


