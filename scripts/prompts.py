DETAIL_SCHEMA = """\
{"summary": "", "deadline": null, "eligibility": "", "action": "", "value": ""}"""

DETAIL_INSTRUCTIONS = """\
你在读一篇校园公告的正文。抽取对学生行动有用的信息，不要复述全文。

summary：50 字以内说清这是什么活动。
deadline：报名/提交截止日期 "YYYY-MM-DD"，正文里没有就 null。绝对不要编造。
eligibility：参与资格（年级、专业、身份限制），没有就空字符串。
action：学生具体要做什么（在哪报名、交什么材料），30 字以内。
value：参与能得到什么（奖项、学分、证书、奖金），没有就空字符串。

只输出 JSON。"""


def detail_messages(title: str, body: str) -> list[dict]:
    return [{
        "role": "user",
        "content": DETAIL_INSTRUCTIONS + f"\n\n标题：{title}\n\n正文：\n{body}",
    }]